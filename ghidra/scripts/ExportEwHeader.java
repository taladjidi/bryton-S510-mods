// ExportEwHeader.java — read-only: write the /EW structures (built by EwStructs.java) as a C header, with
// _Static_assert(sizeof == descriptor size) per class so a C reconstruction compiled against it checks the layouts.
// Args: <header file> <EW_CLASSES.csv>
import ghidra.app.script.GhidraScript;
import ghidra.program.model.data.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;

public class ExportEwHeader extends GhidraScript {
    PrintWriter out;
    Set<String> done = new HashSet<>();

    void emit(Structure s) {                         // dependencies first; undefined runs collapse to byte arrays
        if (!done.add(s.getName())) return;
        for (var c : s.getDefinedComponents()) if (c.getDataType() instanceof Structure t) emit(t);
        out.println("typedef struct " + s.getName() + " {");
        int off = 0;
        for (var c : s.getDefinedComponents()) {
            if (c.getOffset() > off) out.printf("    uint8_t _0x%x[0x%x];%n", off, c.getOffset() - off);
            out.println("    " + c.getDataType().getName() + " " + c.getFieldName() + ";   /* +0x" + Integer.toHexString(c.getOffset()) + " */");
            off = c.getOffset() + c.getLength();
        }
        if (s.getLength() > off) out.printf("    uint8_t _0x%x[0x%x];%n", off, s.getLength() - off);
        out.println("} " + s.getName() + ";\n");
    }

    @Override
    public void run() throws Exception {
        String[] a = getScriptArgs();
        var dtm = currentProgram.getDataTypeManager();
        out = new PrintWriter(a[0]);
        out.println("/* ew_classes.h — Embedded Wizard class layouts of the S510 R039 UI, GENERATED by");
        out.println(" * ghidra/scripts/ExportEwHeader.java from the EW_<Class> structures (EwStructs.java). Do not edit.");
        out.println(" * super = ancestor class at offset 0; m<off>_<Class> = embedded member object found in <Class>__Init;");
        out.println(" * _0x<off> = not yet understood. Sizes are checked against the class descriptors (word[4]). */");
        out.println("#ifndef EW_CLASSES_H\n#define EW_CLASSES_H\n\n#include <stdint.h>\n");
        for (DataType t : dtm.getCategory(new CategoryPath("/EW")).getDataTypes()) if (t instanceof Structure s) emit(s);
        for (String l : Files.readAllLines(Path.of(a[1])).subList(1, Files.readAllLines(Path.of(a[1])).size())) {
            String[] p = l.split(",");
            out.println("_Static_assert(sizeof(EW_" + p[1] + ") == 0x" + Integer.toHexString(getInt(toAddr(p[0]).add(16))) + ", \"" + p[1] + "\");");
        }
        out.println("\n#endif");
        out.close();
    }
}
